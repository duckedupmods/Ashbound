def sh(name, pal, base, ov="", at=0):
    g = [list(r.ljust(16, ".")) for r in base.split()] if base else [list("." * 16) for _ in range(16)]
    for y, row in enumerate(ov.strip("\n").split("\n") if ov.strip() else []):
        for x, c in enumerate(row):
            if c != "." and c != " ":
                g[at + y][x] = "." if c == "_" else c
    I(name, pal, "\n".join("".join(r) for r in g))


