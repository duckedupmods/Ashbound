def gs(name, pal, marks=()):
    g = [list(r.ljust(16, ".")) for r in GS.split()]
    for y, x, c in marks:
        g[y][x] = c
    I(name, pal, "\n".join("".join(r) for r in g))


def core(c, *ys):
    return [(y, 14 - y, c) for y in ys]


