BADGE = {  # 7x7
    "plus": ["..###..", "..#+#..", "###+###", "#+++++#", "###+###", "..#+#..", "..###.."],
    "star": ["...#...", "..#*#..", "###*###", "#*****#", ".#***#.", "#*#.#*#", "##...##"],
    "x": ["##...##", "#*#.#*#", ".#*#*#.", "..#*#..", ".#*#*#.", "#*#.#*#", "##...##"],
    "up": ["...#...", "..#*#..", ".#***#.", "#*****#", "..#*#..", "..#*#..", "..###.."],
}


def hexrgb(h):
    return tuple(int(h[i:i + 2], 16) for i in (1, 3, 5))


def mix(a, b, f):
    return tuple(round(a[i] + (b[i] - a[i]) * f) for i in range(3))


def icon(motif, colour, badge=None):
    """a 16x16 RGBA icon: the motif in the area's colour, outlined and bevelled, with an optional badge"""
    rows = [r.ljust(16, ".")[:16] for r in M[motif].strip("\n").split("\n")]
    rows = (rows + ["." * 16] * 16)[:16]
    base = hexrgb(colour)
    # keep the main colour readable: lift dark ones, tame very pale ones
    lum = 0.3 * base[0] + 0.59 * base[1] + 0.11 * base[2]
    if lum < 110:
        base = mix(base, (255, 255, 255), 0.25)
    pal = {"#": base, "+": mix(base, (255, 248, 230), 0.55), "*": (255, 170, 70), "w": (255, 250, 235), "k": (40, 30, 26)}
    img = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    px = img.load()
    filled = lambda x, y: 0 <= x < 16 and 0 <= y < 16 and rows[y][x] != "."
    for y in range(16):
        for x in range(16):
            c = rows[y][x]
            if c == ".":
                continue
            col = pal[c]
            if c == "#":
                # bevel: lit from the top left, shadowed bottom right
                if not filled(x - 1, y) or not filled(x, y - 1):
                    col = mix(col, (255, 245, 225), 0.25)
                elif not filled(x + 1, y) or not filled(x, y + 1):
                    col = mix(col, (0, 0, 0), 0.35)
            px[x, y] = col + (255,)
    # the outline, one pixel round every filled one
    out = img.copy()
    op = out.load()
    for y in range(16):
        for x in range(16):
            if px[x, y][3]:
                continue
            if any(0 <= x + dx < 16 and 0 <= y + dy < 16 and px[x + dx, y + dy][3] and rows[y + dy][x + dx] in "#+*w"
                   for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))):
                op[x, y] = (18, 12, 10, 255)
    if badge:
        b = BADGE[badge]
        bp = {"#": (18, 12, 10), "+": (255, 236, 200), "*": (255, 196, 90)}
        for y in range(7):
            for x in range(7):
                ch = b[y][x]
                if ch != ".":
                    op[9 + x, 9 + y] = bp[ch] + (255,)
    return out


def sheet(entries, path, scale=4):
    """a contact sheet of (label, icon) pairs, for looking at them"""
    from PIL import ImageDraw, ImageFont
    cols = 10
    cw, ch = 16 * scale + 90, 16 * scale + 28
    rows = (len(entries) + cols - 1) // cols
    img = Image.new("RGB", (cols * cw + 20, rows * ch + 20), (20, 16, 14))
    d = ImageDraw.Draw(img)
    f = ImageFont.truetype("C:/Windows/Fonts/consola.ttf", 13)
    for i, (label, ic) in enumerate(entries):
        x, y = 10 + (i % cols) * cw, 10 + (i // cols) * ch
        d.rectangle((x + 30, y, x + 30 + 16 * scale + 8, y + 16 * scale + 8), fill=(34, 26, 22), outline=(140, 80, 40))
        img.paste(ic.resize((16 * scale, 16 * scale), Image.NEAREST), (x + 34, y + 4), ic.resize((16 * scale, 16 * scale), Image.NEAREST))
        tw = d.textlength(label, font=f)
        d.text((x + 34 + 8 * scale - tw / 2, y + 16 * scale + 10), label, font=f, fill=(220, 200, 170))
    img.save(path)
