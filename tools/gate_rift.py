"""The gate's tear shapes (the crack approved in tools/blender/gate_rift.py): SHAPES jagged outlines, each baked to
a signed distance field side by side in one atlas, plus the outlines as a Java table (fracture lines and lightning
start on the real lip).
  E:/Steam/steamapps/common/Blender/5.2/python/bin/python.exe tools/gate_rift.py
writes assets/ashbound/textures/misc/gate_rift.png and client/GateRift.java. Atlas layout and DMAX must match
gate_rift.fsh."""
import os, random, struct, zlib
import numpy as np

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "main")
SHAPES = 4
H = 4.9      # half height of the tear (blocks)
WMAX = 1.55  # its widest half width
DMAX = 2.0   # stored as 0.5 + d / (2 DMAX), d in blocks, + outside
EX, EZ = 3.2, H + 2.2  # half extents of one cell
W = 256
HH = int(W * EZ / EX)


def outline(rnd):
    n = 22
    zs, xs = [], []
    x = 0.0
    for i in range(n + 1):
        zs.append(-H + 2 * H * i / n)
        x += rnd.uniform(-0.42, 0.42)
        if rnd.random() < 0.18:
            x += rnd.choice((-1, 1)) * 0.5  # a sharp kink, like glass breaking
        x = max(-0.75, min(0.75, x))
        xs.append(x)
    xs[0] = xs[-1] = (xs[0] + xs[-1]) * 0.25
    right, left = [], []
    for i in range(n + 1):
        t = abs(zs[i]) / H
        w = WMAX * max(0.0, 1 - t) ** 0.75 * (1 - 0.35 * t)
        right.append((xs[i] + w * rnd.uniform(0.6, 1.25), zs[i]))
        left.append((xs[i] - w * rnd.uniform(0.6, 1.25), zs[i]))
    right[0] = left[0] = (xs[0], -H)
    right[-1] = left[-1] = (xs[-1], H)

    def teeth(edge, sgn):
        out = [edge[0]]
        for a, b in zip(edge, edge[1:]):
            out += [((a[0] + b[0]) / 2 + sgn * rnd.uniform(-0.16, 0.22), (a[1] + b[1]) / 2 + rnd.uniform(-0.1, 0.1)), b]
        return out
    return teeth(right, 1) + teeth(left, -1)[::-1][1:-1]  # counter-clockwise: up the right lip, down the left


def sdf(poly):
    X, Z = np.meshgrid(np.linspace(-EX, EX, W), np.linspace(-EZ, EZ, HH))
    P = np.array(poly)
    d = np.full(X.shape, 1e9)
    inside = np.zeros(X.shape, bool)
    for (ax, az), (bx, bz) in zip(P, np.roll(P, -1, axis=0)):
        ex, ez = bx - ax, bz - az
        t = np.clip(((X - ax) * ex + (Z - az) * ez) / (ex * ex + ez * ez + 1e-12), 0, 1)
        d = np.minimum(d, np.hypot(X - ax - t * ex, Z - az - t * ez))
        inside ^= ((az > Z) != (bz > Z)) & (X < ax + (Z - az) * ex / (bz - az + 1e-12))
    return np.clip(0.5 + np.where(inside, -d, d) / (2 * DMAX), 0, 1)


def png(path, grey):
    g = np.round(grey[::-1] * 255).astype(np.uint8)  # row 0 = the top of the tear
    rgba = np.stack([g, g, g, np.full_like(g, 255)], axis=-1)  # RGBA: what Minecraft's texture loader expects
    raw = b"".join(b"\x00" + r.tobytes() for r in rgba)

    def chunk(t, data):
        return struct.pack(">I", len(data)) + t + data + struct.pack(">I", zlib.crc32(t + data) & 0xFFFFFFFF)
    h, w = grey.shape
    with open(path, "wb") as f:
        f.write(b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0))
                + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b""))


def main():
    polys = [outline(random.Random(23 + 17 * i)) for i in range(SHAPES)]
    atlas = np.concatenate([sdf(p) for p in polys], axis=1)
    tex = os.path.join(ROOT, "resources", "assets", "ashbound", "textures", "misc")
    os.makedirs(tex, exist_ok=True)
    png(os.path.join(tex, "gate_rift.png"), atlas)
    rows = ",\n".join("\t\t\t{" + ", ".join("%.3ff, %.3ff" % (x, z) for x, z in p) + "}" for p in polys)
    java = """package com.snoringwalrus.ashbound.client;

/** Generated by tools/gate_rift.py: the tears' outlines (x across, y up from the middle, blocks, counter-clockwise),
 *  the same shapes as the distance fields in textures/misc/gate_rift.png. Don't edit, regenerate. */
final class GateRift {
	private GateRift() {}

	static final float H = %.3ff, EX = %.3ff, EZ = %.3ff, DMAX = %.3ff;
	static final float[][] SHAPES = {
%s};
}
""" % (H, EX, EZ, DMAX, rows)
    with open(os.path.join(ROOT, "java", "com", "snoringwalrus", "ashbound", "client", "GateRift.java"), "w", encoding="utf-8") as f:
        f.write(java)
    print("wrote", atlas.shape, "atlas and", SHAPES, "outlines,", [len(p) for p in polys], "points")


if __name__ == "__main__":
    main()
