# pass 16: the goods tools/goodsgen.py adds (tools/goods_icons.json: shape and colours by archetype); the hand ones above stay
def _generated():
    import json as _j
    import os as _o
    p = _o.path.join(_o.path.dirname(_o.path.abspath(__file__)), "goods_icons.json")
    if not _o.path.exists(p):
        return
    shapes = {"BOWL": BOWL, "PLATE": PLATE, "LOAF": LOAF, "JERKY": JERKY, "SKEWER": SKEWER, "PIE": PIE, "CAKES": CAKES,
              "TANKARD": TANKARD, "BOTTLE": BOTTLE, "CUP": CUP, "FLASK": FLASK, "VIAL": VIAL, "CONE": CONE}
    from weaponicons import ICONS as _have
    for gid, g in _j.load(open(p, encoding="utf-8")).items():
        if gid in _have:
            continue
        if g["drink"]:
            drink(gid, shapes[g["shape"]], g["food"], g["shade"], g["shine"])
        else:
            meal(gid, shapes[g["shape"]], g["food"], g["shade"], g["shine"], g["chunk"])


_generated()
