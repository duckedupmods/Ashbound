def gs(name, pal, marks=(), rows=None):
    g = [list(r.ljust(16, ".")) for r in (rows or GS).split()]
    for y, x, c in marks:
        g[y][x] = c
    if " y=" not in " " + pal:
        pal += " y=c8a050"       # the pommel
    I(name, pal, "\n".join("".join(r) for r in g))


def core(c, *ys):
    """a glowing line down the blade's middle, row by row"""
    return [(y, 13 - y + 1, c) for y in ys]


